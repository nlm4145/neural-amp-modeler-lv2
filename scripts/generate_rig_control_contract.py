#!/usr/bin/env python3
"""Generate the AI/API control contract from the shipped LV2 port definitions."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def generate():
    text = (ROOT / "resources/neural_amp_modeler_rig.ttl.in").read_text()
    rows = []
    for block in text.split("], ["):
        if "lv2:ControlPort, lv2:InputPort" not in block:
            continue
        def field(name):
            return re.search(r"lv2:" + name + r"\s+([-\d.]+)", block)[1]
        symbol = re.search(r'lv2:symbol "([^"]+)"', block)[1]
        unit = re.search(r"units:unit units:(\w+)", block)
        unit = {"db": "dB", "pc": "%", "ms": "ms", "hz": "Hz"}.get(unit[1], "") if unit else ""
        choices = re.findall(r'rdfs:value ([-\d.]+) ; rdfs:label "([^"]+)"', block)
        labels = " | ".join(f"{int(float(v))}={label}" for v, label in choices)
        mask = sum(1 << int(float(v)) for v, _ in choices) if "lv2:integer" in block and choices else 0
        # These ports retain legacy host bounds; new AI/API writes use supported choices only.
        enum_mask = f"{mask}u" if choices else "0u"
        integer = "true" if "lv2:integer" in block else "false"
        rows.append(f'    {{{field("index")}, "{symbol}", {float(field("minimum"))}f, {float(field("maximum"))}f, '
                    f'{float(field("default"))}f, "{unit}", {integer}, {enum_mask}, "{labels}"}},')
    return '''// Generated by scripts/generate_rig_control_contract.py; do not edit.
#pragma once
#include <cmath>
#include <cstdint>

namespace NAMRig {
struct RigControlContract {
  uint32_t port;
  const char* symbol;
  float minimum, maximum, defaultValue;
  const char* unit;
  bool integer;
  uint32_t choiceMask;
  const char* choices;
};
inline constexpr RigControlContract kRigControlContracts[] = {
''' + "\n".join(rows) + '''
};
inline const RigControlContract* rigControlContract(uint32_t port) {
  for (const auto& c : kRigControlContracts) if (c.port == port) return &c;
  return nullptr;
}
inline bool validRigControlValue(const RigControlContract& c, double value) {
  if (!std::isfinite(value) || value < c.minimum || value > c.maximum) return false;
  if (c.integer && std::floor(value) != value) return false;
  if (c.choiceMask && (value < 0 || value >= 32 ||
      !(c.choiceMask & (1u << static_cast<uint32_t>(value))))) return false;
  return true;
}
} // namespace NAMRig
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "src/rig_control_contract.h"
    output = generate()
    if args.check:
        if not path.exists() or path.read_text() != output:
            raise SystemExit("Control contract is stale; run scripts/generate_rig_control_contract.py")
    else:
        path.write_text(output)
